def bottomed(section, dy, h=H62, depth=1):
    """section placed at dy (common.place) with its pools given a floor: the
    water place() carries down under them stops `depth` rows under the
    section (a pool up on the rim has a bottom in the rock, not a shaft of
    water to the level's floor)."""
    out = common.place(section, dy, h)
    for y in range(dy + len(section) + depth, h):
        out[y] = out[y].replace(':', '#')
    return out


