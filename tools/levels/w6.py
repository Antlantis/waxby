def crown_header(rows, section, crown_dx, ring_dxs):
    """The vigil_crown header (deep.gd): the crown candle's absolute column,
    then the columns of the candles it waits for. rows: the level's
    (common.level_rows: its sections placed at its height), or its sections."""
    if not isinstance(rows, common.Rows):
        rows = join(*rows)
    return '%d:%s' % (x_of(rows, section, crown_dx), ','.join(str(x_of(rows, section, d)) for d in ring_dxs))

