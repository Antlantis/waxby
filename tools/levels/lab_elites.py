def anoint_header(sections, picks):
    """The anoint: header from [(section, dx, row, omens, name)]: each a
    placed monster's cell, 'x,y[:Omen+Omen[:Name]]', parts by '; '."""
    rows = join(*sections)
    out = []
    for sec, dx, y, omens, name in picks:
        part = '%d,%d' % (x_of(rows, sec, dx), y)
        if omens or name:
            part += ':' + '+'.join(omens)
        if name:
            part += ':' + name
        out.append(part)
    return '; '.join(out)


