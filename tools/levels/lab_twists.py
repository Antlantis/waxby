"""The twist labs (Build 2): one small level per twist, to see each rule
the way a player meets it. Not on the map's path; open one with
--autoplay=<id> (the bot plays it), or by hand on the Mac with
tools/twist_lab.gd. Each is a flat greybox (theme nave) with a sign saying
what to try, and nothing that can snuff you but carelessness (thorn beds,
no pits). The rules themselves are game/scripts/twists.gd's, read from the
header each lab carries:

  lab-restless      twist: restless      stomped Rattles get up once (a
                                         Rootling beside them doesn't)
  lab-restless-all  twist: restless_all  every ordinary floor kind does (a
                                         Hushling, a pack bringer, doesn't)
  lab-toll          twist: toll          the bell every 16 beats quickens what
                    belt_flip: x0-x1=8   is in view; the belts flip every 8
                                         (music: the carillon, on the tick)
  lab-dark          twist: dark          his light x0.8; lanterns light the way
  lab-omens         twist: omens         Anointed twice as often (the max kept)
  lab-dry           twist: dry           thorns, then altars that heal less
  lab-packs         twist: packs         Hushling packs, Glassmite trios, a
                                         Tickwind file, a Creepbone's partner,
                                         an Unwick's pair
  lab-lamplit       twist: lamplit       soft wax over thorns holds firm by a
                                         lit lantern (the far run doesn't)
  lab-lesson        lesson: Title|Line   an X-1's lesson card, no rule

A lab with no twist header would play exactly as before (a rule never runs
without its header); tests/test_twists.gd plays each rule in levels of its
own and checks these files parse with their headers.
"""
