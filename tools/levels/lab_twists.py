def lab(lid, name, sections, hints, **headers):
    entry = {'id': lid, 'name': name, 'subtitle': lid, 'music': 'chapel', 'theme': 'nave', 'area': 1,
             'hints': hints, 'sections': sections}
    entry.update(headers)
    LEVELS.append(entry)


