def swap(sec, cells):
    """A copy of sec with cells {(x, y): glyph} changed (its overlay kept)."""
    rows = [list(r) for r in sec]
    for (x, y), ch in cells.items():
        rows[y][x] = ch
    out = Section(''.join(r) for r in rows)
    out.overlay = getattr(sec, 'overlay', None)
    return out

