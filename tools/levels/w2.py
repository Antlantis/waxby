# Build 2: the switchback's three tiers, each 8 rows (6 of air over its
# floor), stacked: T1 (rows 16-23) going right, T2 (rows 8-15) back left,
# T3 (rows 0-7, its floor one row thick) right again to the gate. Each
# piece is drawn on a section's rows 7-14 (common.crop: rows 0-6 bare), so
# its rows are the tier's as drawn; the terraces span two tiers (_storey).

def _storey(sec, y0, y1, roof=0):
    """Rows y0..y1-1 of sec as a section of their own (one storey of a
    stack), under roof rows of stone: common.crop cuts only bare rows, and
    the terraces climb from one tier into the next."""
    out = common.Section(['#' * len(sec[0])] * roof + list(sec[y0:y1]))
    out.source = getattr(sec, 'source', None) or sec
    out.dy = getattr(sec, 'dy', 0) - y0 + roof
    out.flip = getattr(sec, 'flip', False)
    return out


